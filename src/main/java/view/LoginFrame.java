    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = txtUsername.getText().trim();
        char[] password = pwdPassword.getPassword();

        // Validasi input kosong
        if (username.isEmpty() || password.length == 0) {
            JOptionPane.showMessageDialog(this, "Username dan password wajib diisi.");
            return;
        }

        // Ubah kursor jadi loading dan nonaktifkan tombol sementara
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        btnLogin.setEnabled(false);

        try {
            // Autentikasi user ke database melalui UserDAO
            User user = userDAO.authenticate(username, password);
            if (user == null) {
                JOptionPane.showMessageDialog(this,
                    "Login gagal. Periksa username, password, atau status user.",
                    "Login Gagal", JOptionPane.WARNING_MESSAGE);
                pwdPassword.setText("");
                pwdPassword.requestFocus();
                return;
            }

            // Simpan session user dan buka DashboardFrame
            UserSession.setCurrentUser(user);
            dispose(); // Tutup LoginFrame
            SwingUtilities.invokeLater(() -> new DashboardFrame().setVisible(true));

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                "Tidak dapat mengakses database: " + ex.getMessage(),
                "Database Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            // Bersihkan password di memori untuk keamanan
            Arrays.fill(password, '\0');
            btnLogin.setEnabled(true);
            setCursor(Cursor.getDefaultCursor());
        }
    }//GEN-LAST:event_btnLoginActionPerformed

